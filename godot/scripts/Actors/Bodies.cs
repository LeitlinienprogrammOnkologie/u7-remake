    public static bool IsBodyShape(int shape) => BodyShapes.Contains(shape);

    /// <summary>Exult <c>Shape_info::has_body_info</c> / <c>get_body_shape</c> / <c>get_body_frame</c>.</summary>
    public static bool TryGetBody(int npcShape, out int bodyShape, out int bodyFrame)
    {
        if (BodyList.TryGetValue(npcShape, out var b))
        {
            bodyShape = b.Shape;
            bodyFrame = b.Frame;
            return true;
        }

        bodyShape = 0;
        bodyFrame = 0;
        return false;
    }
